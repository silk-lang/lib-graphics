// Canonical WGSL and its generated Silk modules both belong to lib-graphics.
import { readFileSync, writeFileSync } from 'node:fs';
import { basename, resolve } from 'node:path';
import { root } from './internal.mjs';

const sets = [
  ['graphics/gpu_scene', ['scene', 'blend+compose', 'blend+filter']],
  ['graphics/ui_renderer', ['common+quad', 'common+shadow', 'common+underline', 'common+sprite+mono', 'common+sprite+poly', 'common+path', '../../gpu_scene/shaders/blend+layer']],
];
const stale = [];
for (const [directory, shaders] of sets) {
  // Preserve the original generated format so extraction does not change shader bytes.
  let text = `// Generated by scripts/embed-shaders from ${directory}/shaders; do not edit.\n`;
  for (const shader of shaders) {
    const parts = shader.split('+');
    const source = parts.map(part => readFileSync(resolve(root, directory, 'shaders', part + '.wgsl'), 'utf8')).join('');
    const literal = JSON.stringify(source).replace(/[\u007f-\uffff]/g, char => '\\u' + char.charCodeAt(0).toString(16).padStart(4, '0'));
    text += `pub fn ${basename(parts.at(-1)).replaceAll('-', '_')}() -> &'static [u8] { return b${literal} }\n`;
  }
  const path = resolve(root, directory, 'src/generated_shaders.silk');
  if (process.argv.includes('--check')) {
    if (readFileSync(path, 'utf8') !== text) stale.push(path);
  } else writeFileSync(path, text);
}
if (stale.length) throw new Error(`Stale embedded WGSL: ${stale.join(', ')}; run node scripts/embed-shaders.mjs`);
